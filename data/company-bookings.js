const { applyMarkup, resolveMarkup } = require('../lib/markup');
const { getCompanyById } = require('./companies');

function priced({ basePerPerson, guests, companyId, trip = {} }) {
  const company = getCompanyById(companyId) || {};
  const split = applyMarkup(basePerPerson, resolveMarkup(trip, company));
  const seats = Number(guests) || 1;
  return {
    seats,
    rooms: Math.max(1, Math.ceil(seats / 2)),
    roomType: seats === 1 ? 'single' : 'double',
    occupancy: seats === 1 ? 1 : 2,
    basePrice: split.base * seats,
    markupAmount: split.markup * seats,
    totalPrice: split.total * seats,
  };
}

