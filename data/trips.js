function addDays(iso, days) {
  const date = new Date(`${iso}T12:00:00`);
  date.setDate(date.getDate() + days);
  return date.toISOString().slice(0, 10);
}

function makeRooms(basePrice, counts = { single: 4, double: 10, triple: 3, quad: 2 }) {
  return [
    { type: 'single', occupancy: 1, price: Math.round(basePrice * 1.35), totalRooms: counts.single, availableRooms: counts.single },
    { type: 'double', occupancy: 2, price: basePrice, totalRooms: counts.double, availableRooms: counts.double },
    { type: 'triple', occupancy: 3, price: Math.round(basePrice * 0.88), totalRooms: counts.triple, availableRooms: counts.triple },
    { type: 'quad', occupancy: 4, price: Math.round(basePrice * 0.78), totalRooms: counts.quad, availableRooms: counts.quad },
  ].filter((room) => room.totalRooms > 0);
}

function makeDates(prefix, { days, nights, starts, rooms, soldOutIndex = -1 }) {
  return starts.map((start, index) => {
    const soldOut = index === soldOutIndex;
    const dateRooms = rooms.map((room) => ({
      ...room,
      availableRooms: soldOut ? 0 : Math.max(0, room.availableRooms - (index === 0 ? 1 : 0)),
    }));
    const availableSpots = dateRooms.reduce((sum, room) => sum + room.availableRooms * room.occupancy, 0);
    const totalSpots = rooms.reduce((sum, room) => sum + room.totalRooms * room.occupancy, 0);
    return {
      id: `${prefix}-d${index + 1}`,
      startDate: start,
      endDate: addDays(start, nights),
      days,
      nights,
      totalSpots,
      availableSpots: soldOut ? 0 : availableSpots,
      rooms: dateRooms,
    };
  });
}

function leisureItinerary(days, overrides = []) {
  const base = defaultLeisureItinerary(days);
  return base.map((item, index) => ({ ...item, ...(overrides[index] || {}) }));
}

