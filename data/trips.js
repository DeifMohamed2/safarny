const tripsWithInventory = trips.map((trip) => {
  const rooms = makeRooms(trip.price, trip.beds === 4
    ? { single: 2, double: 6, triple: 4, quad: 6 }
    : { single: 4, double: 10, triple: 3, quad: 2 });
  const starts = trip.type === 'umrah'
    ? ['2026-10-05', '2026-11-02', '2026-12-07']
    : ['2026-10-12', '2026-11-09', '2026-12-14'];
  const travelDates = makeDates(trip.id, {
    days: trip.days,
    nights: trip.nights,
    starts,
    rooms,
    soldOutIndex: trip.soldOut ? 0 : -1,
  });
  if (trip.soldOut) {
    travelDates.forEach((date) => {
      date.availableSpots = 0;
      date.rooms = date.rooms.map((room) => ({ ...room, availableRooms: 0 }));
    });
  }
  const availableSeats = travelDates.reduce((sum, date) => sum + date.availableSpots, 0);
  return {
    ...trip,
    roomTypes: rooms,
    travelDates,
    totalSeats: rooms.reduce((sum, room) => sum + room.totalRooms * room.occupancy, 0),
    availableSeats: trip.soldOut ? 0 : availableSeats,
    availableSpots: trip.soldOut ? 0 : travelDates[0].availableSpots,
    startDate: travelDates[0].startDate,
    endDate: travelDates[0].endDate,
    catalog: true,
    status: trip.soldOut ? 'sold-out' : 'active',
  };
});

function getTripById(id) {
  return tripsWithInventory.find((trip) => String(trip.id) === String(id)) || null;
}

